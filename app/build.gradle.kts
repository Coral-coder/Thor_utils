    signingConfigs {
        // CI injects a release keystore when the secrets are present; without them
        // the release build falls back to the debug key so that a plain
        // `assembleRelease` still produces an installable APK.
        create("release") {
            val storePath = System.getenv("THOR_KEYSTORE_PATH")
            if (!storePath.isNullOrBlank() && file(storePath).exists()) {
                storeFile = file(storePath)
                storePassword = System.getenv("THOR_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("THOR_KEY_ALIAS")
                keyPassword = System.getenv("THOR_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (System.getenv("THOR_KEYSTORE_PATH").isNullOrBlank()) {
                signingConfigs.getByName("debug")
            } else {
                signingConfigs.getByName("release")
            }
        }
    }

